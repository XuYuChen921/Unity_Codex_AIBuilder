        public static string Text(string value) => !Chinese && English.TryGetValue(value, out var translated) ? translated : value;
        public static string Choose(string chinese, string english) => Chinese ? chinese : english;
        public static void DrawSelector()
        {
            using (new EditorGUILayout.HorizontalScope())
            {
                GUILayout.FlexibleSpace();
                var next = EditorGUILayout.Popup(Chinese ? 1 : 0, new[] { "English", "简体中文" }, GUILayout.Width(110));
                if ((next == 1) == Chinese) return;
                EditorPrefs.SetBool(Key, next == 1);
                foreach (var window in Resources.FindObjectsOfTypeAll<EditorWindow>()) window.Repaint();
                SceneView.RepaintAll();
            }
        }
